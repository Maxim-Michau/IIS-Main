"""Generate time-held-out categorisation and clarification measurements."""

from datetime import date
import logging
from pathlib import Path

from scripts.simulate_user import run_simulation


ABLATIONS = (
    ("rules", "Rules only"),
    ("fuzzy", "Rules + fuzzy"),
    ("ml", "Rules + fuzzy + ML"),
    ("context", "Rules + fuzzy + ML + context/recurrence"),
)


def evaluate() -> dict[str, object]:
    """Run each ablation with and without MCC and compare feedback impact."""
    measurements: dict[str, object] = {
        "generated_on": date.today().isoformat(),
        "ablations": {},
        "feedback_comparison": {},
    }
    results: dict[str, dict[str, object]] = {}
    for stage, label in ABLATIONS:
        for with_mcc in (True, False):
            key = f"{stage}_{'with_mcc' if with_mcc else 'without_mcc'}"
            measured = run_simulation(
                months=6,
                pipeline_stage=stage,
                with_mcc=with_mcc,
                apply_feedback=True,
            )
            results[key] = measured
            measurements["ablations"][key] = {
                "label": label,
                "with_mcc": with_mcc,
                **measured,
            }
    feedback_run = results["context_with_mcc"]
    no_feedback = run_simulation(
        months=6,
        pipeline_stage="context",
        with_mcc=True,
        apply_feedback=False,
    )
    measurements["feedback_comparison"] = {
        "with_feedback": feedback_run["week_5_plus_accuracy"],
        "without_feedback": no_feedback["week_5_plus_accuracy"],
        "without_feedback_queued_backlog": no_feedback["queued_backlog"],
        "without_feedback_pending_backlog": no_feedback["pending_backlog"],
    }
    measurements["weekly_context_with_mcc"] = feedback_run["weekly"]
    return measurements


def render_report(measurements: dict[str, object]) -> str:
    """Format freshly measured values into the checked-in evaluation report."""
    ablations = measurements["ablations"]
    lines = [
        "# Evaluation Results",
        "",
        f"Generated by `python -m scripts.evaluate` on "
        f"{measurements['generated_on']}. The script writes this file directly; "
        "the values are not hand-edited.",
        "",
        "Each run uses the chronological synthetic dataset, `build_pipeline`, "
        "the app's `AppService.ingest_all` batch path, and a simulated daily clock. "
        "Weeks 1-2 show initial-period predictions; weeks 5+ are the held-out "
        "later-period predictions after online feedback for runs that enable it. "
        "The optional remote LLM is disabled so results are repeatable and offline.",
        "",
        "| Pipeline ablation | MCC | Accuracy weeks 1-2 | Accuracy weeks 5+ (held out) | Category questions/week | Queued backlog | Pending backlog |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for stage, label in ABLATIONS:
        for with_mcc in (True, False):
            key = f"{stage}_{'with_mcc' if with_mcc else 'without_mcc'}"
            result = ablations[key]
            lines.append(
                f"| {label} | {'yes' if with_mcc else 'no'} | "
                f"{result['week_1_2_accuracy']:.2%} | "
                f"{result['week_5_plus_accuracy']:.2%} | "
                f"{result['category_questions_per_week']:.2f} | "
                f"{result['queued_backlog']} | {result['pending_backlog']} |"
            )

    feedback = measurements["feedback_comparison"]
    change = feedback["with_feedback"] - feedback["without_feedback"]
    if change > 0:
        feedback_outcome = f"improved held-out accuracy by {change:.2%}."
    elif change < 0:
        feedback_outcome = f"reduced held-out accuracy by {abs(change):.2%}."
    else:
        feedback_outcome = "did not improve held-out accuracy."
    lines.extend([
        "",
        "## Feedback impact",
        "",
        f"On the full cascade with MCC, held-out accuracy was "
        f"{feedback['with_feedback']:.2%} with simulated feedback and "
        f"{feedback['without_feedback']:.2%} without it. Simulated feedback "
        f"{feedback_outcome} The no-feedback run ended with "
        f"{feedback['without_feedback_queued_backlog']} queued and "
        f"{feedback['without_feedback_pending_backlog']} pending questions.",
        "",
        "## Weekly questions and backlog",
        "",
        "The following full-cascade/MCC run reports created question counts and "
        "the end-of-week queue sizes. Category questions/week in the table above "
        "uses the total number created divided by the reporting weeks.",
        "",
        "| Week | Week starting | Category questions | All questions | Queued backlog | Pending backlog |",
        "|---:|---|---:|---:|---:|---:|",
    ])
    for week in measurements["weekly_context_with_mcc"]:
        lines.append(
            f"| {week['week']} | {week['week_start']} | "
            f"{week['category_questions']} | {week['all_questions']} | "
            f"{week['queued_backlog']} | {week['pending_backlog']} |"
        )
    lines.extend([
        "",
        "Synthetic MCC values use shared and generic codes, with some missing "
        "values; they are not derived one-to-one from hidden categories. "
        "Locations stay near the generated home area except for occasional "
        "multi-day trips. These measurements describe this synthetic sample only "
        "and are not claims about real bank data.",
        "",
    ])
    return "\n".join(lines)


def main() -> None:
    """Run evaluations and persist the measured Markdown report."""
    logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")
    report_path = Path(__file__).resolve().parents[1] / "docs" / "evaluation_results.md"
    report_path.write_text(render_report(evaluate()), encoding="utf-8")
    logging.info("Wrote measured evaluation report to %s", report_path)


if __name__ == "__main__":
    main()
